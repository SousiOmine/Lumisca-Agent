/**
 * Frontend-safe shared helpers (see shared/mod.ts): pure functions and
 * constants with no runtime dependencies (no db, no Node APIs), bundled into
 * the browser client.
 *
 * Visuals: the images an agent may put inside its reply. An agent publishes
 * a file with the visual tool, the session's store keeps a copy, and the
 * reply embeds it as an image link that names the copy:
 *
 *     ![chart](visual:9f3c2a1b4d5e.png)
 *
 * Only the store's own names are addressable, so a message can never point
 * at a path on the machine (the store generated the name, and the asset
 * route serves nothing else). This module is the single definition of that
 * reference, its name shape and its limits: the tool, the store, the asset
 * route and the markdown renderer all read them here, so a name the tool
 * accepted is a name the route will serve.
 */

/** Scheme of an image link that names a published visual. */
import {
  RASTER_IMAGE_MIME_BY_EXTENSION,
  SVG_EXTENSION,
  SVG_MIME_TYPE,
} from "./mime.ts";

export const VISUAL_REF_SCHEME = "visual:";

/** Content type per extension a visual asset may carry. The same map
 * decides what the visual tool accepts, what the store writes and what the
 * asset route answers with.
 *
 * The rasters come from the shared table (./mime.ts); SVG is added here
 * because this is the only store that accepts it — a reply embeds a visual
 * through an `<img>`, which sandboxes the script an SVG may carry. */
export const VISUAL_MIME_BY_EXTENSION: Readonly<Record<string, string>> = {
  ...RASTER_IMAGE_MIME_BY_EXTENSION,
  [SVG_EXTENSION]: SVG_MIME_TYPE,
};

/** The extensions of VISUAL_MIME_BY_EXTENSION, in a stable order (error
 * messages list them). */
export const VISUAL_EXTENSIONS: readonly string[] = Object.keys(
  VISUAL_MIME_BY_EXTENSION,
);

/** Largest raster image a session may publish (also the largest body the
 * asset route ever serves). Bounded by the federation proxy: a peer's asset
 * is fetched through it, and that request carries a whole-response
 * deadline. */
export const MAX_VISUAL_ASSET_BYTES = 4 * 1024 * 1024;

/** Largest SVG, whether published as a file or drawn in a fence. */
export const MAX_VISUAL_SVG_BYTES = 256 * 1024;

/** Largest asset of one extension: the one limit every writer and reader
 * agrees on (the tool checks a file before reading it, the store checks the
 * bytes it is handed, the fence checks its own source). */
export function maxVisualBytes(extension: string): number {
  return extension.toLowerCase() === SVG_EXTENSION
    ? MAX_VISUAL_SVG_BYTES
    : MAX_VISUAL_ASSET_BYTES;
}

/** Asset name: 12 hex characters and one supported extension. The name is
 * generated by the store (never by the model), so it can neither collide
 * with a path nor be guessed. */
const ASSET_NAME = /^[0-9a-f]{12}\.(png|jpg|jpeg|gif|webp|bmp|svg)$/;

/** The extension an asset may be stored under, or undefined when visuals
 * do not support it. Accepts an extension with its dot, in any case. */
export function isVisualExtension(extension: string): boolean {
  return extension.toLowerCase() in VISUAL_MIME_BY_EXTENSION;
}

/** The content type of an asset name, or undefined when the name is not a
 * valid asset name (shape and extension are checked together: this is the
 * only validator, so nothing downstream can accept a name the route would
 * reject). */
export function visualMimeType(name: string): string | undefined {
  if (!ASSET_NAME.test(name)) return undefined;
  return VISUAL_MIME_BY_EXTENSION[name.slice(name.lastIndexOf("."))];
}

/** The image link that names an asset, as it appears in a reply. */
export function visualRef(name: string): string {
  return `${VISUAL_REF_SCHEME}${name}`;
}

/** The asset an image link names, or undefined when the link is not a
 * visual reference at all (a normal URL) or does not carry a valid name. */
export function parseVisualRef(href: string): string | undefined {
  if (!href.startsWith(VISUAL_REF_SCHEME)) return undefined;
  const name = href.slice(VISUAL_REF_SCHEME.length);
  return visualMimeType(name) === undefined ? undefined : name;
}
