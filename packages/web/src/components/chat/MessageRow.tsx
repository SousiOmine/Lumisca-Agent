import {
  contentImages,
  contentText,
  splitChatText,
} from "@lumisca/core/shared";
import type {
  AgentMessage,
  AssistantMessage,
  CheckpointMessage,
  ModeMessage,
  ToolCallBlock,
  ToolResultMessage,
} from "../../types.ts";
import { ToolCall } from "../ToolCall.tsx";

import { NotificationRow } from "../NotificationRow.tsx";
import { CheckpointRow } from "../CheckpointRow.tsx";
import { CardView } from "./CardView.tsx";
import { CopyableUserMessage } from "./CopyableUserMessage.tsx";
import { MarkdownBlock } from "./MarkdownBlock.tsx";
import { modeRewindText } from "../../slashCommands.ts";
import type { UserMessageImage } from "./types.ts";

/** One message of a turn: user messages get the action row, notifications
 * are compact rows, mode messages show the short text + badge, assistant
 * messages render text + tool calls. `visualBase` is the session's asset
 * base, forwarded to the markdown renderer (see MarkdownBlock). */
export function MessageRow({
  message,
  toolResults,
  runningTools,
  visualBase,
  onRewind,
  onCardSend,
}: {
  message: AgentMessage;
  toolResults: Map<string, ToolResultMessage>;
  runningTools: Map<string, string>;
  visualBase: string;
  /** Sends a card's answer as the user's next message. */
  onCardSend: (text: string) => void;
  onRewind?: (
    timestamp: number,
    text: string,
    images: UserMessageImage[],
  ) => void;
}) {
  if (message.role === "toolResult") return null;

  // System notifications are compact one-line rows, not user messages.
  if (message.role === "notification") {
    return <NotificationRow message={message} />;
  }

  // A compaction checkpoint (older history condensed to free context) is a
  // compact row: the summary is model-facing text, not a user prompt.
  if (message.role === "checkpoint") {
    return <CheckpointRow message={message as CheckpointMessage} />;
  }

  // Mode messages (generated by slash commands like /review) show the
  // short text + mode badge instead of the full prompt. Images attached to
  // the prompt render like a user message's (the model receives them too —
  // see toLlmMessages). The rewind action restores the mode's command line
  // (`/plan 依頼文`) and those images for text-taking modes, so a re-send
  // re-enters the mode instead of degrading to a plain message.
  if (message.role === "mode") {
    const modeMsg = message as ModeMessage;
    return (
      <CopyableUserMessage
        text={modeMsg.shortText}
        images={contentImages(modeMsg.images)}
        timestamp={modeMsg.timestamp}
        modeLabel={modeMsg.modeLabel}
        rewindText={modeRewindText(modeMsg.modeId, modeMsg.shortText)}
        onRewind={onRewind ?? (() => {})}
      />
    );
  }

  // A routine's run is delivered as the user's prompt, but its text is the
  // routine's standing instruction — written down when the routine was
  // created, not typed by the user. The transcript draws what the run
  // answered, not the order that started it. The message stays in the
  // history — a turn is grouped by it (see buildTurns), and hiding it here
  // rather than dropping it there keeps that grouping and the turn's timing.
  if (message.role === "user" && message.routine !== undefined) return null;

  if (message.role === "user") {
    const text = contentText(message.content);
    const imageBlocks = contentImages(message.content);
    return (
      <CopyableUserMessage
        text={text}
        images={imageBlocks}
        timestamp={message.timestamp}
        onRewind={onRewind ?? (() => {})}
      />
    );
  }

  const assistant = message as AssistantMessage;
  const text = contentText(assistant.content);
  const toolCalls = assistant.content.filter(
    (b): b is ToolCallBlock => b.type === "toolCall",
  );
  // A card is a block of the text (see shared/ui-markup/segments.ts), so it
  // is drawn where the agent wrote it — including in the log of a turn that
  // went on working after showing it.
  const segments = splitChatText(text);

  return (
    <div className="msg">
      <div className="msg-body markdown">
        {segments.map((segment, index) =>
          segment.type === "card"
            ? (
              <CardView
                key={index}
                markup={segment.markup}
                onSend={onCardSend}
              />
            )
            : (
              <MarkdownBlock
                key={index}
                text={segment.text}
                visualBase={visualBase}
              />
            )
        )}
        {toolCalls.map((tc) => (
          <ToolCall
            key={tc.id}
            toolCall={tc}
            result={toolResults.get(tc.id)}
            running={runningTools.has(tc.id)}
          />
        ))}
      </div>
    </div>
  );
}
